/**
 * PRODUCTION CONTENT DUMP
 * ------------------------------------------------------------------------
 * Emits idempotent INSERTs for the catalogue and the note corpus, ready to
 * paste into the Neon SQL Editor.
 *
 * WHY A DUMP RATHER THAN A SEED SCRIPT
 *
 * Nexus is unreachable from this machine on 5432 - the network blocks
 * every outbound port except 443 - so a script cannot write to it. That
 * is why the SQL files in this directory exist at all. A dump keeps the
 * one manual step to a single paste, and it is reviewable before it runs:
 * this file is content, not code, and you can read every row it inserts.
 *
 * WHY IT IS IDEMPOTENT
 *
 * Every statement is an INSERT ... ON CONFLICT DO UPDATE. Running it
 * twice changes nothing and running it after a partial run finishes the
 * job. A plain INSERT would fail on the second run and leave you unsure
 * how far it got.
 *
 * WHY EMBEDDINGS ARE NOT COPIED
 *
 * note_chunks.embedding is a pgvector column. The dump writes NULL for it
 * rather than copying bytea across, because a vector produced by a
 * different model or dimension is worse than no vector: it will match
 * nothing, or worse, match badly. Nullable by design - re-embedding is a
 * separate, explicit step, and the tutor degrades to keyword retrieval
 * until then.
 *
 * WHAT IS DELIBERATELY NOT HERE
 *
 * purchases. Those are per-reader and belong to a real payment, so no
 * purchase is invented here. grant-purchase.mjs adds one for a named
 * email, deliberately refusing to run anywhere but localhost.
 *
 * Usage:
 *   $env:DATABASE_URL = "<local DATABASE_URL>"
 *   node packages/db/scripts/dump-content.mjs > production-content.sql
 */
import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { Client } from "pg";

const HERE = dirname(fileURLToPath(import.meta.url));

/** Postgres single-quoted literal. Doubling the quote is the escape. */
const lit = (v) => {
  if (v === null || v === undefined) return "NULL";
  if (typeof v === "number") return String(v);
  if (typeof v === "boolean") return v ? "TRUE" : "FALSE";
  if (v instanceof Date) return `'${v.toISOString()}'`;
  return `'${String(v).replace(/'/g, "''")}'`;
};

/**
 * One table's worth of upserts.
 *
 * Columns are listed explicitly rather than discovered from the row, so a
 * column added to the schema later cannot silently appear in a dump.
 */
async function table(client, name, columns, { transform } = {}) {
  const { rows } = await client.query(`select ${columns.join(", ")} from ${name} order by 1`);
  const out = [];
  for (const row of rows) {
    const values = transform ? transform(row) : columns.map((c) => row[c]);
    const collist = columns.join(", ");
    const valuelist = values.map(lit).join(", ");
    const updates = columns
      .filter((c) => c !== columns[0])
      .map((c) => `${c} = excluded.${c}`)
      .join(", ");
    out.push(
      `insert into ${name} (${collist}) values (${valuelist})\n  on conflict (${columns[0]}) do update set ${updates};`,
    );
  }
  return { name, count: rows.length, statements: out };
}

const url = process.env.DATABASE_URL;
if (!url) {
  console.error("DATABASE_URL must point at a database holding the content to dump.");
  process.exit(1);
}

const client = new Client({ connectionString: url });
await client.connect();

const dumps = [];

dumps.push(
  await table(client, "modules", [
    "id", "code", "name", "description", "price_cents",
    "has_trial_pdf", "status", "sort_order", "created_at", "updated_at",
  ]),
);

dumps.push(
  await table(client, "note_topics", [
    "id", "module_code", "slug", "title", "description",
    "source_path", "content_hash", "page_count", "created_at", "updated_at",
  ]),
);

/*
 * embedding forced to NULL - see the note at the top of this file.
 */
dumps.push(
  await table(
    client,
    "note_chunks",
    ["id", "topic_id", "module_code", "chunk_index", "heading", "content", "token_estimate", "created_at"],
    { transform: (row) => columns_values(row) },
  ),
);

function columns_values(row) {
  return [
    row.id, row.topic_id, row.module_code, row.chunk_index,
    row.heading, row.content, row.token_estimate, row.created_at,
  ];
}

await client.end();

const total = dumps.reduce((n, d) => n + d.count, 0);

const header = [
  "-- PRODUCTION CONTENT FOR NEXUS",
  "-- Generated by packages/db/scripts/dump-content.mjs. Review before running.",
  `-- ${total} rows: ${dumps.map((d) => `${d.name} ${d.count}`).join(", ")}`,
  "-- Idempotent: safe to run more than once.",
  "-- note_chunks.embedding is left NULL and must be re-generated for the tutor.",
  "",
].join("\n");

const body = dumps
  .map((d) => `-- ---- ${d.name} (${d.count}) ${"-".repeat(Math.max(0, 46 - d.name.length))}\n${d.statements.join("\n\n")}`)
  .join("\n\n");

const out = `${header}\n${body}\n`;
writeFileSync(join(HERE, "production-content.sql"), out, "utf8");

/*
 * Verified rather than assumed: the statement count is recomputed from what
 * was actually written, because a silently truncated file is worse than no
 * file - it looks complete.
 */
const written = (out.match(/^insert into /gm) ?? []).length;
const comments = (out.match(/^-- ---- /gm) ?? []).length;

console.log(`rows read   : ${total}`);
console.log(`inserts     : ${written}`);
console.log(`table blocks: ${comments}`);
console.log(`consistent  : ${written === total && comments === dumps.length}`);
for (const d of dumps) {
  const got = d.statements.length;
  console.log(`  ${d.name.padEnd(14)} ${d.count} rows -> ${got} statements ${got === d.count ? "OK" : "MISMATCH"}`);
}
if (written !== total) process.exitCode = 1;