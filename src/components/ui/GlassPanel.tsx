/**
 * THE PANEL
 * ---------------------------------------------------------------------------
 * THE CONTAINER.
 *
 * Every surface in this app that sits on the page is this component, and it
 * is deliberately ONE component, because the treatment is subtle enough that
 * four slightly different panels read as four different products.
 *
 * THE TREATMENT, LAYER BY LAYER
 * ---------------------------------------------------------------------------
 * Bottom to top:
 *
 *   1. FILL. The palette's own `bg1` — the raised surface, one step off the
 *      page. It is OPAQUE, because the page behind it is a flat colour and
 *      there is nothing behind it to show.
 *
 *   2. GRAIN. The reference for this treatment is
 *      https://hermes-agent.nousresearch.com/, which overlays a fractal
 *      noise tile on its containers — and only on its containers, never on
 *      the page. The tile is generated by `scripts/generate-grain.mjs` from
 *      the same `feTurbulence` recipe that site uses, and it is applied
 *      HERE and nowhere else, which is the whole point of it: grain over a
 *      large flat area reads as dirt, grain over a small panel reads as a
 *      material.
 *
 *   3. EDGE. A hairline in the palette's own `line` colour — the same
 *      hairline every other bordered surface in the app uses, so a panel
 *      and an input beside it are the same kind of thing. Along the top of
 *      it, a one-pixel sheen in the foreground colour: the highlight that
 *      tells you a surface has a surface under it.
 *
 *   4. ROUNDED CORNERS. `RADIUS.panel`, unless the caller says otherwise.
 *      The radius is a prop rather than a hard-coded style, so a container
 *      that wants a different curve says so here.
 *
 * WHY THE EDGE IS NOT IN THE ACCENT COLOUR
 * ---------------------------------------------------------------------------
 * It was, once, and it read as a red rim drawn around every surface in the
 * app — a hairline so small that on most of the palettes it looked like a
 * rendering fault rather than a decision. The accent is for the things the
 * accent is FOR: the thing that is selected, the thing that is live, the
 * one thing on a screen that matters. A border on every panel is not that.
 */
import { type ReactNode } from "react";
import { Image, StyleSheet, View, type StyleProp, type ViewStyle } from "react-native";

import { useActiveTheme } from "@/theme/ThemeProvider";
import { RADIUS } from "@/theme/radius";

/**
 * The grain tiles.
 *
 * `grain-light.png` is white speckle, for a dark palette; `grain-dark.png`
 * is the same field in black, for a light one, where white grain would be
 * invisible and black grain reads as the tooth of the paper.
 */
const GRAIN_LIGHT = require("../../../assets/images/grain-light.png");
const GRAIN_DARK = require("../../../assets/images/grain-dark.png");

export type PanelStrength = "soft" | "medium" | "solid";

export type GlassPanelProps = {
  children: ReactNode;
  style?: StyleProp<ViewStyle>;
  /** Padding inside the panel. */
  padding?: number;
  /**
   * How much the panel leans on its own background.
   *
   * The page is `bg0` and the panel is `bg1`, so the strengths are the
   * steps between them: `soft` is a barely-there step, `solid` is the
   * furthest the palette's own surfaces go.
   */
  strength?: PanelStrength;
  /** Set false to drop the hairline edge. */
  bordered?: boolean;
  /**
   * The corner radius, in points. `RADIUS.panel` is the house style; a
   * container that opts out of it says so here rather than by hard-coding
   * a style.
   */
  radius?: number;
};

export function GlassPanel({
  children,
  style,
  padding = 22,
  strength = "medium",
  bordered = true,
  radius = RADIUS.panel,
}: GlassPanelProps): React.JSX.Element {
  const theme = useActiveTheme();
  const dark = theme.group === "dark";

  /*
   * The grain sits UNDER the content and OVER the fill, so it is a texture
   * on the panel rather than a texture floating above it.
   */
  const grain = (
    <Image
      source={dark ? GRAIN_LIGHT : GRAIN_DARK}
      style={[StyleSheet.absoluteFill, { opacity: dark ? 0.14 : 0.1 }]}
      resizeMode="repeat"
      pointerEvents="none"
    />
  );

  return (
    <View
      style={[
        styles.panel,
        {
          borderRadius: radius,
          backgroundColor: theme.tokens.bg1,
          borderColor: theme.tokens.line,
        },
        bordered ? null : styles.unbordered,
        style,
      ]}
    >
      {grain}

      {/*
       * 2 — THE SHEEN ALONG THE TOP EDGE.
       *
       * A one-pixel highlight, in the foreground colour and not the
       * accent's. It is what tells you a surface has a surface under it,
       * and it is the same idea the terminal's own bar carries.
       *
       * It is a strip rather than a second border, so the panel's own
       * hairline — the one the palette's `line` colour draws — is what
       * outlines the shape, and the sheen only brightens the top of it.
       * The panel's `overflow: hidden` clips it to the rounded corner,
       * so the highlight follows the curve rather than running past it.
       */}
      {bordered ? (
        <View
          style={[styles.sheen, { backgroundColor: `${theme.tokens.fg}1F` }]}
          pointerEvents="none"
        />
      ) : null}

      {/* 3 — the content */}
      <View style={{ padding }}>{children}</View>
    </View>
  );
}

const styles = StyleSheet.create({
  panel: {
    // ROUNDED CORNERS, by default. The radius is a prop, so a container
    // that opts out of the house style says so rather than by hard-coding
    // a style here. See `STYLING.md` §1.2.
    borderRadius: RADIUS.panel,
    borderWidth: StyleSheet.hairlineWidth,
    // The grain and the content are clipped to the rounded shape, so the
    // corner is a real corner and not a square with a rounded mask over
    // it.
    overflow: "hidden",
  },
  unbordered: {
    borderWidth: 0,
  },
  sheen: {
    position: "absolute",
    top: 0,
    left: 0,
    right: 0,
    height: StyleSheet.hairlineWidth,
  },
});
